"""Round Robin ``FormatEngine`` — the reference format implementation.

Every competitor meets every other once per cycle (``cycles`` config → single/double
round robin). Fixtures are generated by the **circle method**: one competitor is
fixed and the rest rotate, producing balanced rounds where each competitor plays once
per round. Odd counts add a bye slot (that competitor rests the round — no match).

Pure + deterministic: fixtures depend only on the (already seeded) participant order,
except when an ``rng_seed`` is given, in which case the initial order is shuffled
reproducibly. Sport-agnostic — it pairs opaque participant ids, so singles and doubles
(and any sport) work unchanged.
"""

from __future__ import annotations

import random
from collections.abc import Mapping
from typing import Any

from app.engine.contracts import GenerateRequest
from app.engine.errors import EngineValidationError, Issue
from app.engine.source_refs import ParticipantSideRef, SourceRefs
from app.engine.types import FormatKey, GroupPlan, MatchPlan, RoundPlan, StructurePlan

_GROUP_KEY = "G1"


class RoundRobinFormat:
    """Satisfies ``app.engine.FormatEngine`` for ``FormatKey.ROUND_ROBIN``."""

    key = FormatKey.ROUND_ROBIN

    def validate_config(self, config: Mapping[str, Any]) -> None:
        cycles = config.get("cycles", 1)
        if not (isinstance(cycles, int) and not isinstance(cycles, bool) and cycles >= 1):
            raise EngineValidationError(
                [Issue("cycles", "invalid", "cycles must be a positive integer")]
            )

    def generate(self, request: GenerateRequest) -> StructurePlan:
        self.validate_config(request.config)
        ids = [p.id for p in request.participants]

        issues: list[Issue] = []
        if len(ids) < 2:
            issues.append(
                Issue("participants", "too_few", "round robin needs at least 2 participants")
            )
        if len(set(ids)) != len(ids):
            issues.append(Issue("participants", "duplicate", "participant ids must be unique"))
        if issues:
            raise EngineValidationError(issues)

        if request.rng_seed is not None:
            ids = list(ids)
            random.Random(request.rng_seed).shuffle(ids)

        cycles = int(request.config.get("cycles", 1))
        group = GroupPlan(key=_GROUP_KEY, name="Round Robin", participant_ids=tuple(ids))

        # Circle method: fix slot 0, rotate the rest. Odd count → a bye slot (None).
        slots: list[str | None] = list(ids)
        if len(slots) % 2 == 1:
            slots.append(None)
        size = len(slots)
        half = size // 2
        rounds_per_cycle = size - 1

        rounds: list[RoundPlan] = []
        matches: list[MatchPlan] = []
        round_seq = match_seq = 0
        for _cycle in range(cycles):
            order = list(slots)
            for _ in range(rounds_per_cycle):
                round_seq += 1
                round_key = f"R{round_seq}"
                rounds.append(RoundPlan(key=round_key, seq=round_seq, label=f"Round {round_seq}"))
                for i in range(half):
                    home, away = order[i], order[size - 1 - i]
                    if home is None or away is None:
                        continue  # bye — that competitor rests this round
                    match_seq += 1
                    matches.append(
                        MatchPlan(
                            key=f"M{match_seq}",
                            source_refs=SourceRefs(
                                (ParticipantSideRef(home), ParticipantSideRef(away))
                            ),
                            round_key=round_key,
                            group_key=_GROUP_KEY,
                        )
                    )
                # rotate everything except slot 0 (clockwise)
                order = [order[0], order[-1], *order[1:-1]]

        return StructurePlan(
            format=self.key,
            groups=(group,),
            rounds=tuple(rounds),
            matches=tuple(matches),
        )
