import * as React from "react";

import { cn } from "@/lib/utils";

/**
 * Card — white, 2px ink, 1.5rem radius, 6px sticker shadow (design system §5/§6).
 * `hoverable` adds the Expressive-tier lift; leave off for Functional/dense surfaces.
 */
export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }
>(({ className, hoverable = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "border-ink bg-card text-card-foreground shadow-sticker-md rounded-2xl border-2",
      hoverable &&
        "ease-bouncy hover:shadow-sticker-lg transition-[transform,box-shadow] duration-150 hover:-translate-x-[3px] hover:-translate-y-[3px] hover:rotate-[-1deg]",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

export const CardHeader = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div ref={ref} className={cn("flex flex-col gap-1.5 p-6", className)} {...props} />
  ),
);
CardHeader.displayName = "CardHeader";

